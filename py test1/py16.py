#1.__init__() 和 __new__() 方法
# __init__() 方法是一个实例方法，在创建对象后会自动调用，用于初始化对象的属性和状态，__new__() 方法是一个静态方法，在创建对象之前会自动调用，用于创建对象并返回对象的实例，__new__() 方法通常用于实现单例模式或者元类等高级功能，而 __init__() 方法则用于初始化对象的属性和状态。
