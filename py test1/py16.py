# 2.单例模式
#是一种常用的软件设计模式,主要目的是确保某一个类中只有一个实例存在,
#可以节省内存空间,增加代码的复用性
#可以理解成一个特殊的类,这个类只存在一个对象
#弊端:多线程访问的时候容易引发线程安全问题
