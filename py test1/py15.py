# 总结
# 1.实例方法:方法内部访问实例属性,方法内部可以通过类名,类属性名来访问类属性
# 2.静态方法@static method:方法内部,不需要访问实例属性和类属性
#如果要访问类属性,可以通过类名.类属性名来访问,不能访问实例属性
# 3.类方法@classmethod:方法内部访问类属性,方法内部可以通过cls.类属性名来访问类属性,不能访问实例属性
class Person(object):
    name = "张三"  #类属性，所有对象共享
    def instance_method(self):  #实例方法的第一个参数是self，表示实例本身，可以通过self来访问实例的属性和方法，也可以通过类名.类属性名来访问类属性，因为实例方法是绑定到实例上的方法，所以可以访问实例的属性和方法，也可以访问类的属性和方法。
        self.age = 18  #实例属性，只有当前对象可以访问
        print(f"这是一个实例方法，名字是：{Person.name},年龄是：{self.age}")
    @staticmethod
    def static_method(name): #静态方法没有self参数，不能访问实例的属性和方法，只能访问传入的参数，因为静态方法与类无关，所以不能访问实例的属性和方法，只能访问传入的参数。
        print(f"这是一个静态方法，名字是：{name}")
    @classmethod
    def class_method(cls):  #类方法的第一个参数是cls，表示类本身，可以通过cls来访问类的属性和方法，但不能访问实例的属性和方法，因为类方法是绑定到类上的方法，所以不能访问实例的属性和方法，只能访问类的属性和方法。
        print(f"这是一个类方法，名字是：{cls.name}")
p = Person()  #创建一个Person对象p
p.instance_method()  #调用实例方法，输出：这是一个实例方法，名字是：张三,年龄是：18，实例方法可以通过对象来调用，因为实例方法是绑定到实例上的方法，所以可以通过对象来调用实例方法
Person.static_method("李四")  #调用静态方法，输出：这是一个静态方法，名字是：李四，静态方法可以直接通过类名来调用，不需要创建对象，因为静态方法与类无关，所以不需要创建对象来调用静态方法
p.static_method("王五")  #调用静态方法，输出：这是一个静态方法，名字是：王五，静态方法也可以通过对象来调用，但不推荐，因为静态方法与类无关，所以不需要创建对象来调用静态方法，直接通过类名来调用就可以了，这样可以提高代码的可读性和可维护性。
Person.class_method()  #调用类方法，输出：这是一个类方法，名字是：张三，类方法可以直接通过类名来调用，不需要创建对象，因为类方法是绑定到类上的方法，所以不需要创建对象来调用类方法
p.class_method()  #调用类方法，输出：这是一个类方法，名字是：张三，类方法也可以通过对象来调用，但不推荐，因为类方法是绑定到类上的方法，所以不需要创建对象来调用类方法，直接通过类名来调用就可以了，这样可以提高代码的可读性和可维护性。
