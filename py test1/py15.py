# 3.4 多继承的弊端
# 多继承虽然可以让子类同时继承多个父类的属性和方法，但也会带来一些问题，比如方法冲突、属性冲突、代码复杂度增加等，所以在实际开发中，应该尽量避免使用多继承，或者在使用多继承时，应该注意父类之间的关系，避免出现方法冲突和属性冲突的问题，同时也要注意代码的可读性和可维护性。

